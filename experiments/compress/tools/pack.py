#!/usr/bin/env python3
"""Compress the camp-fire data (tiles, sprites, fire frames) in several formats for the TI-89 bench.

Reads games/campfire/data.h (read-only), rebuilds the three raw blobs exactly as the 68000 sees
them (big-endian words/longs), compresses each blob with:
  rle  PackBits-style RLE (host encoder below, C decoder in ../unpack.c)
  lz4  LZ4 block format, HC level 12 (python-lz4), no size prefix
  zx0  ZX0 v2 (einar-saukas/ZX0 built on the host; path in $ZX0, default tools/bin/zx0)
  ttp  ttpack (GCC4TI tools), unpacked on the calculator by ExtGraph's UnpackBuffer
and writes ../pdata.h (one array <fmt><blob> per format x blob, lengths and Fletcher-16 checksums of the raw
blobs) plus a ratio table on stdout. Every stream is decoded back on the host and compared.
Run: tools/pyenv/bin/python experiments/compress/tools/pack.py
"""
import os
import re
import subprocess
import sys
import tempfile
import lz4.block

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
SRC = os.path.join(ROOT, 'games', 'campfire', 'data.h')
ZX0 = os.environ.get('ZX0', os.path.join(ROOT, 'tools', 'bin', 'zx0'))
DZX0 = os.environ.get('DZX0', os.path.join(ROOT, 'tools', 'bin', 'dzx0'))
TTPACK = os.path.join(ROOT, 'tools', 'gcc4ti-bin', 'bin', 'ttpack')
TTUNPACK = os.path.join(ROOT, 'tools', 'gcc4ti-bin', 'bin', 'ttunpack')


def arrays(text):
    """name -> (element size in bytes, list of ints) for every const array of data.h."""
    out = {}
    for m in re.finditer(r'static const unsigned (char|short|long) (\w+)\[[^=]*=\s*\{(.*?)\};', text, re.S):
        size = {'char': 1, 'short': 2, 'long': 4}[m.group(1)]
        vals = [int(v, 0) for v in re.findall(r'0x[0-9A-Fa-f]+|\d+', m.group(3))]
        out[m.group(2)] = (size, vals)
    return out


def be(size, vals):
    return b''.join(v.to_bytes(size, 'big') for v in vals)


def blobs():
    a = arrays(open(SRC).read())
    tiles = be(*a['tiles'])
    spr = b''.join(be(*a[k]) for k in a if re.match(r'[a-z]+\d_[ldm]$', k))
    fire = be(*a['fire_l']) + be(*a['fire_d'])
    return [('tiles', tiles), ('sprites', spr), ('fire', fire)]


# ---------------------------------------------------------------- PackBits RLE
# control byte c: 0..127 -> c+1 literal bytes follow; 128..255 -> next byte repeated 257-c times
# (2..129). A run of 2 is only used between runs (it costs as much as a literal pair).
def rle_pack(d):
    out, lit, i, n = bytearray(), bytearray(), 0, len(d)

    def flush():
        while lit:
            k = min(len(lit), 128)
            out.append(k - 1); out.extend(lit[:k]); del lit[:k]
    while i < n:
        j = i
        while j < n and j - i < 129 and d[j] == d[i]:
            j += 1
        r = j - i
        if r >= 3 or (r == 2 and not lit):
            flush(); out.append(257 - r); out.append(d[i]); i = j
        else:
            lit.append(d[i]); i += 1
    flush()
    return bytes(out)


def rle_unpack(s):
    out, i = bytearray(), 0
    while i < len(s):
        c = s[i]; i += 1
        if c < 128:
            out += s[i:i + c + 1]; i += c + 1
        else:
            out += bytes([s[i]]) * (257 - c); i += 1
    return bytes(out)


def tool(cmd_pack, cmd_unpack, data):
    with tempfile.TemporaryDirectory() as t:
        src, dst, back = os.path.join(t, 'in'), os.path.join(t, 'out'), os.path.join(t, 'back')
        open(src, 'wb').write(data)
        # relative names: ttpack takes any argument starting with '/' for an option (DOS style)
        subprocess.run(cmd_pack('in', 'out'), check=True, capture_output=True, cwd=t)
        packed = open(dst, 'rb').read()
        # no check: the host ttunpack writes the right file, then aborts with a double free()
        subprocess.run(cmd_unpack('out', 'back'), capture_output=True, cwd=t)
        assert open(back, 'rb').read() == data, 'round trip failed: %s' % cmd_pack('in', 'out')
        return packed


def lz4_pack(d):
    c = lz4.block.compress(d, mode='high_compression', compression=12, store_size=False)
    assert lz4.block.decompress(c, uncompressed_size=len(d)) == d
    return c


FORMATS = [
    ('rle', lambda d: rle_pack(d)),
    ('lz4', lz4_pack),
    ('zx0', lambda d: tool(lambda s, o: [ZX0, '-f', s, o], lambda s, o: [DZX0, '-f', s, o], d)),
    ('ttp', lambda d: tool(lambda s, o: [TTPACK, '-quiet', s, o], lambda s, o: [TTUNPACK, s, o], d)),
]


def fletcher16(d):
    a = b = 0
    for x in d:
        a = (a + x) % 255
        b = (b + a) % 255
    return b << 8 | a


def carray(name, d):
    rows = [','.join('%d' % x for x in d[i:i + 32]) for i in range(0, len(d), 32)]
    return 'static const unsigned char %s[%d] = {\n%s};' % (name, len(d), ',\n'.join(rows))


def main():
    bl = blobs()
    assert rle_unpack(rle_pack(bl[0][1])) == bl[0][1]
    c = ['// Generated by tools/pack.py from games/campfire/data.h: do not edit.']
    for k, (nm, d) in enumerate(bl):
        c.append('#define RAW%d_LEN %d\n#define RAW%d_SUM 0x%04X' % (k, len(d), k, fletcher16(d)))
    total_raw = sum(len(d) for _, d in bl)
    print('%-5s' % 'fmt' + ''.join('%16s' % nm for nm, _ in bl) + '%16s' % 'total')
    print('%-5s' % 'raw' + ''.join('%16d' % len(d) for _, d in bl) + '%16d' % total_raw)
    for fn, f in FORMATS:
        packed = [f(d) for _, d in bl]
        assert fn != 'rle' or all(rle_unpack(p) == d for p, (_, d) in zip(packed, bl))
        tot = sum(len(p) for p in packed)
        print('%-5s' % fn + ''.join('%9d %5.1f%%' % (len(p), 100.0 * len(p) / len(d)) for p, (_, d) in zip(packed, bl))
              + '%9d %5.1f%%' % (tot, 100.0 * tot / total_raw))
        for k, p in enumerate(packed):
            c.append(carray('%s%d' % (fn, k), p))
            open(os.path.join(HERE, '..', 'bin', '%s.%s' % (bl[k][0], fn)), 'wb').write(p)
    for k, (nm, d) in enumerate(bl):
        open(os.path.join(HERE, '..', 'bin', '%s.raw' % nm), 'wb').write(d)
    open(os.path.join(HERE, '..', 'pdata.h'), 'w').write('\n'.join(c) + '\n')


if __name__ == '__main__':
    os.makedirs(os.path.join(HERE, '..', 'bin'), exist_ok=True)
    main()
