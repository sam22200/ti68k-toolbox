#!/usr/bin/env python3
"""Generates compiled masked sprites for render1.c (TI-89, 30-byte LCD rows).

Usage: tools/pyenv/bin/python experiments/render/gen_sprites.py > experiments/render/sprgen.h

One 16x16 sprite (4 greys + transparency) is turned into, for each shift s = x & 15:
  - spr_bw_s(p)        : black and white, one plane (black where the sprite has any grey)
  - spr_gr_s(p0, p1)   : grayscale, light plane p0 and dark plane p1
p = row start + ((x >> 4) << 1) (word-aligned, so every access is at an even address).
Each touched 16-bit word gets the cheapest form:
  mask 0xFFFF, data 0    -> nothing (fully transparent)
  mask 0                 -> store data          (move.w/l #imm,d16(a0))
  data == ~mask          -> OR only             (ori)
  data 0                 -> AND only            (andi)
  otherwise              -> AND then OR
and the two words of a row are merged into one long operation when they need the same form.
It also emits the plain ExtGraph data (sprite rows and AND masks, 1 = keep background).
"""

SPRITE = [  # '.' transparent, '0' white, '1' light grey, '2' dark grey, '3' black
    "......3333......",
    "....33222233....",
    "...3211111123...",
    "..321100001123..",
    ".32110000001123.",
    ".32100000000123.",
    "3211000000001123",
    "3210000000000123",
    "3210000000000123",
    "3211000000001123",
    ".32110000001123.",
    ".32211000011223.",
    "..322211112223..",
    "...3322222233...",
    "....33333333....",
    "......3333......",
]
# plane bit per colour: light plane has 1 for light grey and black, dark plane for dark grey and black
LIGHT = {"0": 0, "1": 1, "2": 0, "3": 1}
DARK = {"0": 0, "1": 0, "2": 1, "3": 1}
BW = {"0": 0, "1": 1, "2": 1, "3": 1}


def rows(table):
    data, mask = [], []
    for r in SPRITE:
        d = m = 0
        for c in r:
            d <<= 1
            m <<= 1
            if c == ".":
                m |= 1
            else:
                d |= table[c]
        data.append(d)
        mask.append(m)
    return data, mask


def word_ops(data, mask, s):
    """list of (byte offset, width 2|4, kind, and_mask, or_data) for one plane at shift s"""
    ops = []
    for r, (d, m) in enumerate(zip(data, mask)):
        D = (d << (16 - s)) & 0xFFFFFFFF
        X, n = 0xFFFF0000 | m, 16 - s
        M = ((X << n) | (X >> (32 - n))) & 0xFFFFFFFF    # rol.l #(16-s) of 0xFFFFmmmm, as ExtGraph
        words = []
        for half in (0, 1):
            dw = (D >> (16 - 16 * half)) & 0xFFFF
            mw = (M >> (16 - 16 * half)) & 0xFFFF
            if mw == 0xFFFF and dw == 0:
                kind = None
            elif mw == 0:
                kind = "st"
            elif dw == (~mw & 0xFFFF):
                kind = "or"
            elif dw == 0:
                kind = "and"
            else:
                kind = "andor"
            words.append((kind, mw, dw))
        (k0, m0, d0), (k1, m1, d1) = words
        off = r * 30
        if k0 is not None and k0 == k1:
            ops.append((off, 4, k0, (m0 << 16) | m1, (d0 << 16) | d1))
        else:
            if k0:
                ops.append((off, 2, k0, m0, d0))
            if k1:
                ops.append((off + 2, 2, k1, m1, d1))
    return ops


def emit_ops(ops, p):
    out = []
    for off, w, kind, m, d in ops:
        t = "W" if w == 2 else "L"
        h = "0x%04X" if w == 2 else "0x%08lXUL"
        if kind == "st":
            out.append(f"{t}({p},{off}) = {h % d};")
        elif kind == "or":
            out.append(f"{t}({p},{off}) |= {h % d};")
        elif kind == "and":
            out.append(f"{t}({p},{off}) &= {h % m};")
        else:
            out.append(f"{t}({p},{off}) &= {h % m}; {t}({p},{off}) |= {h % d};")
    return out


def main():
    print("// Generated by experiments/render/gen_sprites.py: do not edit by hand.")
    print("#define W(p, o) (*(unsigned short *)((p) + (o)))")
    print("#define L(p, o) (*(unsigned long *)((p) + (o)))")
    bw, bwm = rows(BW)
    li, lim = rows(LIGHT)
    da, dam = rows(DARK)
    assert lim == dam == bwm
    print("static const unsigned short spr_bw[16] = {" + ", ".join("0x%04X" % v for v in bw) + "};")
    print("static const unsigned short spr_mask[16] = {" + ", ".join("0x%04X" % v for v in bwm) + "};")
    print("static const unsigned short spr_light[16] = {" + ", ".join("0x%04X" % v for v in li) + "};")
    print("static const unsigned short spr_dark[16] = {" + ", ".join("0x%04X" % v for v in da) + "};")
    nops_bw = nops_gr = 0
    for s in range(16):
        ops = word_ops(bw, bwm, s)
        nops_bw += len(ops)
        print(f"static void spr_bw_{s}(unsigned char *p)\n{{")
        for line in emit_ops(ops, "p"):
            print("    " + line)
        print("}")
    for s in range(16):
        o0, o1 = word_ops(li, lim, s), word_ops(da, dam, s)
        nops_gr += len(o0) + len(o1)
        print(f"static void spr_gr_{s}(unsigned char *p0, unsigned char *p1)\n{{")
        for line in emit_ops(o0, "p0") + emit_ops(o1, "p1"):
            print("    " + line)
        print("}")
    print("static void (*const spr_bw_tab[16])(unsigned char *) = {"
          + ", ".join(f"spr_bw_{s}" for s in range(16)) + "};")
    print("static void (*const spr_gr_tab[16])(unsigned char *, unsigned char *) = {"
          + ", ".join(f"spr_gr_{s}" for s in range(16)) + "};")
    print(f"// memory operations: B/W {nops_bw} over 16 shifts, gray {nops_gr}")


main()
