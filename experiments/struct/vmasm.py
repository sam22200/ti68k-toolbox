# Tiny assembler for the vm.c bytecode. Usage: python3 vmasm.py behav.vms
# Writes behav.bin (raw image), behav.h (the same bytes as a C array, for the embedded copy) and
# prints the ttbin2oth command that makes the data file. Syntax: "label:", "OP a, b, c", ".db n, n",
# ";" comments. Registers r0..r7 are emitted pre-scaled (r*2 = byte offset into short v[8]).
# Branch targets are rel8 from the end of the instruction; LDB tables are absolute offsets (< 256).
# Image layout: [entry offsets, one byte per ".entry" label, in order] [code and data].
import sys, re

OPS = {  # name: (opcode, operand kinds)   r = register, i = imm8, b = rel8 branch, a = abs8, n = byte
    'HALT': (0, ''), 'LDI': (1, 'ri'), 'MOV': (2, 'rr'), 'ADD': (3, 'rr'), 'SUB': (4, 'rr'),
    'ADDI': (5, 'ri'), 'ANDI': (6, 'ri'), 'LDB': (7, 'rra'), 'JMP': (8, 'b'), 'JZ': (9, 'rb'),
    'JNZ': (10, 'rb'), 'DJNZ': (11, 'rb'), 'JLTI': (12, 'rib'), 'JEQ': (13, 'rrb'), 'JLT': (14, 'rrb'),
    'YIELD': (15, ''), 'CALL': (16, 'n'),
}

def assemble(src):
    lines, entries = [], []
    for ln in src.splitlines():
        ln = ln.split(';')[0].strip()
        if not ln: continue
        m = re.match(r'(\w+):\s*(.*)', ln)
        if m: lines.append(('label', m.group(1))); ln = m.group(2).strip()
        if not ln: continue
        if ln.startswith('.entry'): entries.append(ln.split()[1]); continue
        op, _, args = ln.partition(' ')
        lines.append(('op', op.upper(), [a.strip() for a in args.split(',') if a.strip()]))
    def size(it):
        return len(it[2]) if it[1] == '.DB' else 1 + len(OPS[it[1]][1])
    labels, pc = {}, len(entries)
    for it in lines:                       # pass 1: addresses
        if it[0] == 'label': labels[it[1]] = pc
        else: pc += size(it)
    out = [labels[e] for e in entries]
    for it in lines:                       # pass 2: bytes
        if it[0] == 'label': continue
        if it[1] == '.DB': out += [int(a) & 255 for a in it[2]]; continue
        code, kinds = OPS[it[1]]
        end = len(out) + size(it)
        out.append(code)
        for k, a in zip(kinds, it[2]):
            if k == 'r': v = int(a.lstrip('r')) * 2
            elif k in 'in': v = int(a)
            elif k == 'a': v = labels[a]
            else:
                v = labels[a] - end
                assert -128 <= v < 128, 'branch out of range: ' + a
            out.append(v & 255)
    assert len(out) < 256, 'LDB offsets are 8-bit'
    return bytes(out), entries, labels

if __name__ == '__main__':
    fn = sys.argv[1]; base = fn.rsplit('.', 1)[0]
    img, entries, labels = assemble(open(fn).read())
    open(base + '.bin', 'wb').write(img)
    with open(base + '.h', 'w') as h:
        h.write('// generated by vmasm.py from %s: do not edit\n' % fn)
        for i, e in enumerate(entries): h.write('#define ENTRY_%s %d\n' % (e.upper(), labels[e]))
        h.write('#define SCRIPT_SIZE %d\n' % len(img))
        h.write('static const unsigned char script[%d] = {%s};\n' % (len(img), ','.join(map(str, img))))
    print('%d bytes, entries %s' % (len(img), {e: labels[e] for e in entries}))
    print('ttbin2oth -89 vms %s.bin vmscr' % base)
