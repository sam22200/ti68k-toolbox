#!/usr/bin/env python3
"""Own placeholder sprite scales; no ROM art. Same sampling as runtime Q8 scaler."""
from pathlib import Path
LEVELS=[4,8,12,16,24,32,48,64]
INK=[0,24,60,60,24,60,126,126,90,24,60,60,36,36,102,0]
OPACITY=[24,60,126,126,126,255,255,255,255,126,126,126,126,255,255,102]
def main():
    data=[];offset=[]
    for pose in range(2):
        ink=INK.copy()
        if pose:ink[12:15]=[36,66,195]
        for h in LEVELS:
            offset.append(len(data));w=h//2;stride=(w+7)//8
            du=((16384+w-1)//w)>>3;dv=((16384+h-1)//h)>>2
            for y in range(h):
                mask=[0]*stride;pixels=[0]*stride;sy=(y*dv)>>8
                for x in range(w):
                    bit=128>>((x*du)>>8);dst=128>>(x&7)
                    if OPACITY[sy]&bit:mask[x>>3]|=dst
                    if ink[sy]&bit:pixels[x>>3]|=dst
                data+=mask+pixels
    text='/* Generated by tools/sprite_tables.py; own placeholder art. */\n'
    root=Path(__file__).resolve().parents[1]
    (root/'tnspr.bin').write_bytes(bytes(data+[i.bit_count() for i in range(256)]))
    for name,kind,values in [('levels','u8',LEVELS),('scale_offset','u16',offset),
                              ('height_level','u8',[min(range(8),key=lambda i:abs(LEVELS[i]-h)) for h in range(65)])]:
        text+=f'static const {kind} {name}[{len(values)}]={{\n'
        text+='\n'.join('    '+','.join(map(str,values[i:i+24]))+',' for i in range(0,len(values),24))+'\n};\n'
    root.joinpath('sprites_data.h').write_text(text)
if __name__=='__main__':main()
