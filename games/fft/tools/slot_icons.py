#!/usr/bin/env python3
"""The source's own equipment-slot pictograms, for the management tabs.

usage: slot_icons.py DISC.cue OUT.h [preview.png]

OBSERVED on the disc: EVENT/FRAME.BIN is the menus' art sheet (256 wide, 4bpp, no palette:
the indices are a grey ramp). Its rows 171..182 carry the five pictograms the source draws
down the left of its EQP. list -- a hand holding a weapon, a hand, a helmet, a ring and a
tunic -- eight to twelve pixels wide each. They are trimmed, centred in a 12x12 cell and
mapped to the runtime's four greys, index 1 (the outline) becoming black so each reads at
a glance on a white list.
"""
import sys
import numpy as np
from PIL import Image
import extract
CUE=sys.argv[1]
disc,files=extract.disc_files(CUE)
b=np.frombuffer(disc.read(*files['EVENT/FRAME.BIN']),np.uint8)
n=np.empty(b.size*2,np.uint8); n[0::2]=b&15; n[1::2]=b>>4
sheet=n[:256*293].reshape(293,256)
# EVENT/FRAME.BIN is the menu sheet: these five are the equipment-slot pictograms the
# source draws down the left of its EQP. list (rows 172..181).
CELLS=[('rhand',0,8),('lhand',8,16),('head',16,24),('acc',24,36),('body',36,48)]
GREY={0:-1}            # 0 transparent; 1 is the outline, 6 the highlight
for v,g in ((1,3),(2,2),(3,2),(4,1),(5,1),(6,0)): GREY[v]=g
rows=[]
prev=[]
for name,x0,x1 in CELLS:
    c=sheet[171:183,x0:x1]
    im=np.array([[GREY.get(int(v),0) for v in r] for r in c])
    # trim empty rows/columns, then centre in a 12x12 cell
    ys=np.flatnonzero((im>=0).any(1)); xs=np.flatnonzero((im>=0).any(0))
    im=im[ys.min():ys.max()+1, xs.min():xs.max()+1]
    cell=np.full((12,12),-1,int)
    oy=(12-im.shape[0])//2; ox=(12-im.shape[1])//2
    cell[oy:oy+im.shape[0], ox:ox+im.shape[1]]=im
    prev.append(cell)
    light=[];dark=[];mask=[]
    for r in range(12):
        l=d=m=0
        for x in range(12):
            v=cell[r][x]
            bit=1<<(15-x)
            if v<0: m|=bit
            else:
                if v&1: l|=bit
                if v&2: d|=bit
        light.append(l);dark.append(d);mask.append(m)
    rows.append((name,light,dark,mask))
out=['// Generated by tools/slot_icons.py from EVENT/FRAME.BIN rows 171..182. Never committed.',
     '// The source\'s own equipment-slot pictograms: R.Hand, L.Hand, Head, Accessory, Body.',
     'static const u16 slot_icon[5][3][12] = {']
for name,l,d,m in rows:
    out.append('    { { %s },' % ', '.join('0x%04X'%v for v in l))
    out.append('      { %s },' % ', '.join('0x%04X'%v for v in d))
    out.append('      { %s } },   // %s' % (', '.join('0x%04X'%v for v in m), name))
out.append('};')
open(sys.argv[2],'w').write('\n'.join(out)+'\n')
# preview
pal=np.array([[255,255,255],[170,170,170],[85,85,85],[0,0,0]],np.uint8)
img=np.zeros((12,12*5,3),np.uint8); img[:]= (235,235,235)
for i,cell in enumerate(prev):
    for y in range(12):
        for x in range(12):
            v=cell[y][x]
            if v>=0: img[y,i*12+x]=pal[v]
if len(sys.argv)>3: Image.fromarray(img).resize((12*5*10,120),Image.NEAREST).save(sys.argv[3])
print('%s: five source slot pictograms, 12x12 in four greys'%sys.argv[2])
